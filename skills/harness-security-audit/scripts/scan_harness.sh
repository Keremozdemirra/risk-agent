#!/usr/bin/env bash
# Mechanical half of harness-security-audit. Reports shapes, never verdicts —
# every hit needs the reachability judgement in SKILL.md before it is a finding.
set -uo pipefail

CLAUDE="${CLAUDE_HOME:-$HOME/.claude}"
OWN="$CLAUDE/skills $CLAUDE/agents $CLAUDE/hooks"
THIRD="$CLAUDE/plugins/cache"
# Folder holding your own repositories: check 5 reads their workflow files, and
# check 8 skips skills linked from there. Set HARNESS_REPOS to point it elsewhere.
REPOS="${HARNESS_REPOS:-$CLAUDE}"
export REPOS
RG="$(command -v rg || true)"
[ -z "$RG" ] && { echo "ripgrep gerekli: brew install ripgrep"; exit 2; }

hdr() { printf '\n=== %s ===\n' "$1"; }
none() { echo "  temiz"; }

hdr "1. Gizli Unicode / bidi"
out=$($RG -nP --no-heading '[\x{200B}\x{200C}\x{200D}\x{2060}\x{FEFF}\x{202A}-\x{202E}]' $OWN 2>/dev/null | head -20)
[ -n "$out" ] && echo "$out" || none

hdr "2. Gömülü yük"
out=$($RG -n --no-heading '<script|data:text/html|base64,' $OWN 2>/dev/null | head -20)
[ -n "$out" ] && echo "$out" || none

hdr "3. Yetki atlama / model yönlendirme (üçüncü taraf dahil)"
out=$($RG -n --no-heading -i \
  'ANTHROPIC_BASE_URL|ANTHROPIC_AUTH_TOKEN|enableAllProjectMcpServers|bypassPermissions|dangerouslySkipPermissions|--dangerously' \
  $OWN "$CLAUDE/settings.json" "$THIRD" 2>/dev/null | head -20)
[ -n "$out" ] && { echo "$out"; echo "  → her biri için: bu dosyayı kim import ediyor? ulaşılabilir mi?"; } || none

hdr "4. Skill/agent gövdesinde giden komut"
out=$($RG -n --no-heading -w 'curl|wget|nc|scp|ssh' $CLAUDE/skills $CLAUDE/agents 2>/dev/null \
      | grep -viE 'example|README|schema' | head -20)
[ -n "$out" ] && echo "$out" || none

hdr "5. Sabitlenmemiş kaynak (@latest / movable tag)"
python3 - <<'PY'
import json, os, glob
hits = []
for p in [os.path.expanduser("~/.claude.json"), os.path.expanduser("~/.claude/settings.json")]:
    if not os.path.exists(p):
        continue
    try:
        d = json.load(open(p))
    except Exception:
        continue
    for name, cfg in (d.get("mcpServers") or {}).items():
        for a in cfg.get("args", []):
            if "@latest" in str(a) or str(a).endswith("@next"):
                hits.append(f"  {p.replace(os.path.expanduser('~'),'~')}  mcp:{name}  {a}")
for f in glob.glob(os.path.join(os.environ["REPOS"], "*/.github/workflows/*.y*ml")):
    for i, line in enumerate(open(f, encoding="utf-8", errors="replace"), 1):
        if "uses:" in line and "@" in line:
            ref = line.split("@")[-1].strip().split()[0]
            if len(ref) != 40:
                hits.append(f"  {f.replace(os.path.expanduser('~'),'~')}:{i}  {line.strip()[:60]}")
print("\n".join(hits) if hits else "  temiz")
PY

hdr "6. Skill'lerde dış bağlantı"
out=$($RG -oN --no-heading 'https?://[a-zA-Z0-9._/-]+' $CLAUDE/skills 2>/dev/null \
      | grep -oE 'https?://[^/]+' | sort | uniq -c | sort -rn | head -10)
[ -n "$out" ] && echo "$out" || none

hdr "7. Üretilen dizine elle yazılmış mı"
$RG -l 'GENERATED|DO NOT EDIT|autogenerated' $CLAUDE/agents $CLAUDE/skills 2>/dev/null | head -5 || none

hdr "8. Lisansı olmayan üçüncü taraf skill"
n=0
REPOS_REAL=$(python3 -c "import os,sys;print(os.path.realpath(sys.argv[1]))" "$REPOS")
for d in "$CLAUDE"/skills/*/; do
  real=$(python3 -c "import os,sys;print(os.path.realpath(sys.argv[1]))" "$d")
  # Only an explicit HARNESS_REPOS marks skills as your own; the default would
  # exempt every copied-in third-party skill.
  if [ -n "${HARNESS_REPOS:-}" ]; then
    case "$real" in
      "$REPOS_REAL"/*) continue ;;
    esac
  fi
  ls "$real" 2>/dev/null | grep -qiE '^licen[sc]e' || { echo "  $(basename "$d")"; n=$((n+1)); }
done
[ "$n" -eq 0 ] && none
echo
echo "Bulgular şekildir, hüküm değil. SKILL.md'deki 'payload mı artefakt mı' adımını uygula."
